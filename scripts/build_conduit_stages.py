#!/usr/bin/env python3
"""Hypothetical locally level cross-section stages; never change native terrain."""
import json,sys,time,hashlib
from pathlib import Path
import numpy as np,rasterio,shapefile
from scipy.ndimage import map_coordinates,distance_transform_edt
from shapely.geometry import shape
from shapely import transform,make_valid,union_all
from pyproj import Transformer
sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
from hydraulics.reach_flow import section_geometry
from hydraulics.water_initialization import polygon_parts
ROOT=Path(__file__).resolve().parents[1];OUT=ROOT/'assets/private/water_system';BASE=ROOT/'assets/private/humanum_danish_edna'


def build():
    executed_source=Path(__file__).read_bytes()
    started=time.monotonic();cfg=json.loads((ROOT/'configs/water_system.json').read_text())
    if not np.isfinite([cfg['conduit_stage_station_spacing_m'],cfg['conduit_bed_percentile'],cfg['conduit_stage_above_bed_m']]).all() or cfg['conduit_stage_station_spacing_m']<=0 or not 0<=cfg['conduit_bed_percentile']<=100 or cfg['conduit_stage_above_bed_m']<0:raise ValueError('Invalid conduit stage parameters')
    source={}
    for r in shapefile.Reader(str(BASE/'angkor_center_features')).iterShapeRecords():
        if int(r.record['TYPE'])==2:source[str(r.record['FID'])]=make_valid(shape(r.shape.__geo_interface__))
    for r in shapefile.Reader(str(BASE/'angkor_center_lineartraces')).iterShapeRecords():
        if int(r.record['TYPE'])==2:source[str(r.record['FID'])]=make_valid(shape(r.shape.__geo_interface__).buffer(cfg['water_trace_width_m']/2))
    to_utm=Transformer.from_crs(4326,32648,always_xy=True)
    features=json.loads((OUT/'reaches.geojson').read_text())['features'];records=[];node_levels={};missing=0;capped_count=0
    with rasterio.open(BASE/'dtm_angkor_center.tif') as src:
        z=src.read(1);z[(z==src.nodata)|~np.isfinite(z)]=np.nan;tf=src.transform;profile=src.profile.copy()
    for f in features:
        p=f['properties'];ids=[sid for sid in p['source_ids'] if sid in source]
        if not ids:continue
        line=transform(shape(f['geometry']),to_utm.transform,interleaved=False);polygon=union_all([source[sid] for sid in ids])
        fractions=np.linspace(0,1,max(2,int(np.ceil(line.length/cfg['conduit_stage_station_spacing_m']))+1));levels=[]
        for fraction in fractions:
            section,tangent,capped=section_geometry(line,polygon,float(fraction))
            if section is None or capped:
                levels.append(np.nan);missing+=1;capped_count+=int(capped);continue
            count=max(2,int(np.ceil(section.length/.5)));points=[section.interpolate((i+.5)/count,normalized=True) for i in range(count)]
            cc,rr=(~tf) @ (np.array([p.x for p in points]),np.array([p.y for p in points]))
            values=map_coordinates(z,[np.asarray(rr)-.5,np.asarray(cc)-.5],order=1,mode='constant',cval=np.nan,prefilter=False)
            valid=values[np.isfinite(values)]
            if valid.size<.9*values.size:levels.append(np.nan);missing+=1;continue
            levels.append(float(np.percentile(valid,cfg['conduit_bed_percentile']))+cfg['conduit_stage_above_bed_m'])
        levels=np.asarray(levels);good=np.isfinite(levels)
        if not good.any():continue
        levels=np.interp(fractions,fractions[good],levels[good])
        for key,level in ((p['from_node'],levels[0]),(p['to_node'],levels[-1])):node_levels.setdefault(key,[]).append(float(level))
        records.append((p,line,fractions,levels))
    # A shared geometric branch gets one initial stage; avoid a high-bank seed
    # generated by a less representative cross-section through that junction.
    nodes={key:min(values) for key,values in node_levels.items()}
    stage=np.full(z.shape,np.nan,np.float32)
    for p,line,fractions,levels in records:
        levels[0]=nodes[p['from_node']];levels[-1]=nodes[p['to_node']]
        points=[line.interpolate(float(t),normalized=True) for t in np.linspace(0,1,max(2,int(np.ceil(line.length/.25))+1))]
        values=np.interp(np.linspace(0,1,len(points)),fractions,levels)
        cc,rr=(~tf) @ (np.array([p.x for p in points]),np.array([p.y for p in points]));rr=np.floor(rr).astype(int);cc=np.floor(cc).astype(int)
        valid=(rr>=0)&(rr<z.shape[0])&(cc>=0)&(cc<z.shape[1]);stage[rr[valid],cc[valid]]=values[valid]
    (OUT/'conduit_stage_profiles.json').write_text(json.dumps([{'reach_id':p['id'],'fractions':fractions.tolist(),'stages_m':levels.tolist()} for p,line,fractions,levels in records],separators=(',',':')))
    seeded=np.isfinite(stage);print('Cross-section stage seeds',int(seeded.sum()),flush=True)
    if not seeded.any():raise ValueError('No valid conduit stage seeds')
    # Nearest centerline is only used inside mapped conduits at initialization;
    # this does not create a flow connection across the intervening terrain.
    indices=distance_transform_edt(~seeded,return_distances=False,return_indices=True)
    stage=stage[indices[0],indices[1]];del indices,z
    profile.update(driver='GTiff',dtype='float32',count=1,nodata=-9999,tiled=True,blockxsize=512,blockysize=512,compress='deflate',predictor=3,zlevel=1,BIGTIFF='IF_SAFER',NUM_THREADS='4');profile.pop('interleave',None)
    tmp=OUT/'conduit_stages.tmp.tif'
    with rasterio.open(tmp,'w',**profile) as dst:dst.write(stage,1);dst.set_band_description(1,'hypothetical local cross-section-derived conduit water stage, m; use within mapped conduits only')
    tmp.replace(OUT/'conduit_stages.tif')
    report={'method':'Local cross-section bed percentile plus offset, stages interpolated along candidate reaches; junction level is the minimum adjacent estimate; nearest centerline stages applied only to mapped conduit pixels outside storage.',
        'station_spacing_m':cfg['conduit_stage_station_spacing_m'],'bed_percentile':cfg['conduit_bed_percentile'],'depth_offset_m':cfg['conduit_stage_above_bed_m'],
        'seed_cells':int(seeded.sum()),'reaches_with_stages':len(records),'unresolved_station_samples':missing,'capped_station_samples':capped_count,'wall_s':time.monotonic()-started,
        'limits':['Hypothetical water surface, not surveyed bathymetry or a steady solution.','Interpolation avoids water on every high bank of a broad canal polygon.','No terrain burn-in; high bed pixels remain dry when above the assumed local stage.','Nearest-centerline interpolation does not impose hydraulic links.','Per-storage levels override conduit-stage interpolation within storage polygons.'],
        'source_states':{str(f.relative_to(ROOT)):{'size':f.stat().st_size,'mtime_ns':f.stat().st_mtime_ns} for f in [OUT/'reaches.geojson',BASE/'dtm_angkor_center.tif',ROOT/'configs/water_system.json']}}
    digest=hashlib.sha256(executed_source).hexdigest();snapshots=OUT/'code_snapshots';snapshots.mkdir(exist_ok=True)
    snapshot=snapshots/(digest+'_build_conduit_stages.py');snapshot.write_bytes(executed_source)
    report.update(code_sha256=digest,code_snapshot=str(snapshot))
    (OUT/'conduit_stages.json').write_text(json.dumps(report,indent=2));print(json.dumps(report),flush=True)

if __name__=='__main__':build()
